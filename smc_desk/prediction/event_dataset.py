import pandas as pd
from typing import List, Dict, Any

class EventDatasetBuilder:
    """
    Builds the non-survivorship-biased dataset of all candidate setups 
    generated by the state machine, including failures, expirations,
    and unresolved episodes.
    """
    def __init__(self):
        self.events: List[Dict[str, Any]] = []
        
    def record_candidate(self, 
                         setup_id: str, 
                         timestamp: pd.Timestamp, 
                         state: str,
                         features: Dict[str, Any],
                         outcome_target: bool = False,
                         outcome_stop: bool = False,
                         outcome_unresolved: bool = True,
                         bars_to_resolution: int = 0) -> None:
        """
        Record a candidate state event along with its known outcome.
        
        This prevents survivorship bias by demanding all events (not just completed trades)
        are registered for training.
        """
        outcomes = [bool(outcome_target), bool(outcome_stop), bool(outcome_unresolved)]
        if sum(outcomes) != 1:
            raise ValueError("Exactly one outcome must be true: target_first, stop_first, or unresolved.")

        event = {
            "setup_id": setup_id,
            "decision_time": timestamp,
            "state": state,
            **features,
            "target_first": outcome_target,
            "stop_first": outcome_stop,
            "unresolved": outcome_unresolved,
            "bars_to_resolution": bars_to_resolution
        }
        self.events.append(event)
        
    def get_dataset(self) -> pd.DataFrame:
        """
        Convert the recorded events into a structured pandas DataFrame suitable for modeling.
        """
        return pd.DataFrame(self.events)
